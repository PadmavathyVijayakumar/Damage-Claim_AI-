"""
Dispute letter generator.

Auto-generates structured dispute letters for claims where the warehouse
evidence shows the damage was pre-existing or carrier-caused.

Each letter includes:
  - Timestamped evidence references (inbound scan, outbound scan, COC events)
  - Severity comparison (inbound classification vs claimant's assertion)
  - Temperature log excerpts (for cold-chain excursion claims)
  - S3 links to supporting images and sensor data
  - Legal-safe boilerplate (without providing legal advice)
"""
from __future__ import annotations

import logging
from dataclasses import dataclass
from datetime import datetime
from typing import Optional

from .comparator import ComparisonResult
from .chain_of_custody import ChainOfCustodyRecord

logger = logging.getLogger(__name__)


@dataclass
class DisputeLetter:
    """A generated dispute letter for one claim."""

    claim_id: str
    sscc: str
    generated_at: str
    subject: str
    body: str                        # Full letter text (Markdown)
    evidence_references: list[str]   # S3 keys cited in the letter
    recommended_action: str          # "reject_claim" | "accept_partial" | "escalate"


class DisputeLetterGenerator:
    """
    Generates dispute letters from evidence packages and COC records.

    Usage:
        gen = DisputeLetterGenerator(company_name="Mindwave Logistics")
        letter = gen.generate(
            claim_id=...,
            comparison=comparator_result,
            coc_record=custody_record,
        )
        # letter.body is Markdown — render or send via email/WMS attachment
    """

    def __init__(
        self,
        company_name: str = "Mindwave Logistics",
        contact_email: str = "claims@mindwave.ai",
    ) -> None:
        self.company_name = company_name
        self.contact_email = contact_email

    def generate(
        self,
        claim_id: str,
        comparison: ComparisonResult,
        coc_record: Optional[ChainOfCustodyRecord] = None,
        claimant_name: str = "Retailer",
        claim_amount: Optional[float] = None,
        additional_notes: str = "",
    ) -> DisputeLetter:
        """
        Generate a dispute letter.

        Args:
            claim_id:        Internal claim ID.
            comparison:      Output from ConditionComparator.compare().
            coc_record:      Chain-of-custody record for this SSCC.
            claimant_name:   Name of the retailer / claimant.
            claim_amount:    Claimed amount in USD (optional).
            additional_notes: Free-text supplement.

        Returns:
            DisputeLetter with Markdown body.
        """
        now = datetime.utcnow().strftime("%B %d, %Y")
        evidence_refs: list[str] = []

        # Determine recommended action
        if comparison.should_reject_claim:
            recommended_action = "reject_claim"
            action_text = "respectfully dispute and reject"
        elif comparison.carrier_responsible:
            recommended_action = "escalate"
            action_text = "redirect to the carrier"
        else:
            recommended_action = "accept_partial"
            action_text = "accept under review"

        # Build COC timeline section
        coc_section = self._build_coc_section(coc_record, evidence_refs)

        # Build comparison section
        comparison_section = self._build_comparison_section(comparison, evidence_refs)

        # Build letter body
        amount_line = f"**Claimed Amount:** ${claim_amount:,.2f}\n" if claim_amount else ""
        body = f"""# Damage Claim Dispute Notice

**Date:** {now}
**Claim ID:** {claim_id}
**SSCC (Pallet ID):** {comparison.sscc}
**Claimant:** {claimant_name}
{amount_line}
---

Dear {claimant_name},

This letter is a formal response to your damage claim (ID: `{claim_id}`) filed
against {self.company_name}. After a thorough review of our automated inspection
records, chain-of-custody documentation, and sensor logs, we {action_text} this
claim for the reasons outlined below.

---

## 1. Automated Condition Assessment

{comparison_section}

---

## 2. Chain of Custody Timeline

{coc_section}

---

## 3. Evidence References

The following evidence files are available upon request:

{self._format_evidence_list(evidence_refs)}

---

## 4. Conclusion and Next Steps

**AI System Verdict:** {comparison.evidence_summary}

**Recommended Action:** `{recommended_action}`
**Confidence:** {comparison.confidence:.0%}

{self._build_conclusion(recommended_action, claimant_name)}

{f'**Additional Notes:** {additional_notes}' if additional_notes else ''}

---

*This notice was generated by the Mindwave AI Claims Intelligence Platform.
Evidence images and sensor data are archived in our secure S3 evidence store.
Please contact {self.contact_email} with the claim ID to request full evidence disclosure.*

Regards,
{self.company_name} Claims Team
"""

        logger.info(
            "Dispute letter generated claim_id=%s action=%s",
            claim_id, recommended_action,
        )
        return DisputeLetter(
            claim_id=claim_id,
            sscc=comparison.sscc,
            generated_at=datetime.utcnow().isoformat() + "Z",
            subject=f"RE: Damage Claim Dispute — {claim_id}",
            body=body,
            evidence_references=evidence_refs,
            recommended_action=recommended_action,
        )

    def _build_comparison_section(
        self, comparison: ComparisonResult, evidence_refs: list[str]
    ) -> str:
        lines = [
            f"| Field | Inbound | Outbound |",
            f"|---|---|---|",
            f"| Condition | {comparison.inbound_severity.upper()} | {comparison.outbound_severity.upper()} |",
            f"| Visual Similarity | — | {comparison.similarity_score:.1%} |",
            f"| Origin | {comparison.damage_origin.replace('_', ' ').title()} | — |",
        ]
        return "\n".join(lines)

    def _build_coc_section(
        self,
        coc_record: Optional[ChainOfCustodyRecord],
        evidence_refs: list[str],
    ) -> str:
        if coc_record is None:
            return "_No chain-of-custody record available for this SSCC._"

        lines = []
        for event in sorted(coc_record.events, key=lambda e: e.timestamp_iso):
            lines.append(
                f"- **{event.point.replace('_', ' ').title()}** "
                f"({event.timestamp_iso[:16]}) — "
                f"{event.location} — Condition: **{event.pallet_condition}**"
            )
            for key in event.image_s3_keys:
                evidence_refs.append(key)

        return "\n".join(lines) if lines else "_No custody events recorded._"

    @staticmethod
    def _format_evidence_list(refs: list[str]) -> str:
        if not refs:
            return "_No specific evidence items referenced._"
        return "\n".join(f"- `{r}`" for r in refs)

    @staticmethod
    def _build_conclusion(action: str, claimant_name: str) -> str:
        if action == "reject_claim":
            return (
                f"Based on the evidence above, {claimant_name}'s claim is hereby **rejected**. "
                "Our records show the damage was present before the goods entered our custody. "
                "We recommend {claimant_name} direct this claim to the originating supplier."
            )
        if action == "escalate":
            return (
                "Our records indicate the goods were in good condition at the time of carrier pickup "
                "(verified by seal number and BOL). We recommend this claim be **redirected to the carrier**."
            )
        return (
            "We are reviewing this claim under our standard SLA. "
            "We will respond with a final determination within 5 business days."
        )
